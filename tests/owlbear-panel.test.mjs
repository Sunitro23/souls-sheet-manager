import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {fresh,entry} from '../lib/rules.ts';
import {defaultTree} from '../lib/progression.ts';
test('Owlbear navigation keeps play resources accessible and public initiative totals visible and private details hidden',async()=>{
 const folder=await mkdtemp(resolve('.openai/owlbear-render-'));
 try{
  await build({stdin:{contents:"export {default as Panel} from './components/owlbear-panel';export {default as Initiative} from './components/owlbear-initiative';",resolveDir:process.cwd(),loader:'tsx'},outfile:join(folder,'ui.mjs'),bundle:true,platform:'node',format:'esm',packages:'external',jsx:'automatic',plugins:[{name:'workspace-test',setup(b){b.onResolve({filter:/use-owlbear-combat$/},()=>({path:'runtime',namespace:'runtime-test'}));b.onLoad({filter:/.*/,namespace:'runtime-test'},()=>({contents:"export function useOwlbearCombat(){return globalThis.__owlbearRuntime??{combat:null,state:null,playerId:'alice',ready:true,error:''}}",loader:'js'}));b.onResolve({filter:/^@owlbear-rodeo\/sdk$/},()=>({path:'sdk',namespace:'sdk-test'}));b.onLoad({filter:/.*/,namespace:'sdk-test'},()=>({contents:'export default {};export const buildShape=()=>{},buildPath=()=>{},isImage=()=>false,Command={};',loader:'js'}));b.onResolve({filter:/workspace-client$/},()=>({path:'workspace',namespace:'test'}));b.onLoad({filter:/.*/,namespace:'test'},()=>({contents:'export async function workspaceCall(){throw Error("Unexpected call")} export async function characterForOwlbear(){throw Error("Unexpected call")}',loader:'js'}));}}]});
  const {Panel,Initiative}=await import(pathToFileURL(join(folder,'ui.mjs')).href);
  const character={...fresh(),name:'Hero',inventory:[entry('Fiole','consumable',{status:'approved',effects:'Restaure des PV'})]};
  const props={ready:false,campaignId:'campaign',campaigns:[{id:'campaign',name:'Campagne'}],characters:[character],character,canAssign:false,section:'Personnage',tree:defaultTree(),busy:false,dirty:false,saveStatus:'idle',conflict:false};
  const panel=renderToStaticMarkup(React.createElement(Panel,props));
  assert.match(panel,/Navigation Owlbear/);
  assert.match(panel,/>Hero<\/strong>/);
  assert.match(panel,/Connexion à Owlbear/);
  assert.match(panel,/Retirer 1 PV/);
  const dirtyPanel=renderToStaticMarkup(React.createElement(Panel,{...props,dirty:true,saveStatus:'saving'}));
  assert.doesNotMatch(dirtyPanel,/>Enregistrer<\/button>/);
  assert.match(dirtyPanel,/Enregistrement…/);
  assert.match(panel,/Ajouter 1 END/);
  assert.doesNotMatch(panel,/>Personnage<|Campagne active|Personnage actif|Équipement et sorts|Caractéristiques|Fiole/);
  const actions=renderToStaticMarkup(React.createElement(Panel,{...props,ready:true,section:'Actions'}));
  assert.match(actions,/Hors combat/);
  assert.match(actions,/Objets disponibles/);
  assert.match(actions,/aria-label="Fiole"/);
  for(const label of ['PV','FP','END'])assert.ok(actions.includes(`aria-label="${label}"`));
  const gmPanel=renderToStaticMarkup(React.createElement(Panel,{...props,canAssign:true}));
  assert.match(gmPanel,/aria-label="Paramètres GM"/);
  assert.doesNotMatch(gmPanel,/Campagne active|Personnage actif/);
  const combat={version:1,id:'combat',revision:1,phase:'ready',participants:[{id:'hero',characterId:character.id,name:'Hero',dex:14,playerId:'alice'},{id:'enemy',name:'Enemy',dex:24,playerId:'gm'}],initiative:{rolls:[{participantId:'hero',d20:20,source:'manual'},{participantId:'enemy',d20:1,source:'manual'}],tieOrder:['hero','enemy'],collector:null}};
  const player=renderToStaticMarkup(React.createElement(Initiative,{combat,canManage:false,playerId:'alice',connectionId:'alice'}));
  assert.match(player,/c-owlbear-footer/);assert.match(player,/Terminer mon tour/);assert.match(player,/Enemy/);assert.match(player,/<b title="Initiative">8<\/b>/);assert.match(player,/aria-current="step"/);
  assert.match(player,/c-turn-strip/);
  assert.match(player,/Tour de : <strong>Hero/);
  assert.match(player,/c-turn-portrait/);
  assert.doesNotMatch(player,/c-owlbear-active-info|Manche 1/);
  assert.doesNotMatch(player,/c-owlbear-current|>Actions<|Esquive/);
  assert.doesNotMatch(player,/DEX : 24|Gérer les tours|Tour précédent/);
  globalThis.__owlbearRuntime={combat:{...combat,turn:1},state:{combat:{...combat,turn:1},pending:null,resolution:null},playerId:'alice',ready:true,error:''};
  const waiting=renderToStaticMarkup(React.createElement(Panel,{...props,ready:true,section:'Actions'}));
  assert.match(waiting,/Retirer 1 PV/);
  assert.match(waiting,/Objets disponibles/);
  assert.match(waiting,/Tour de Enemy — en attente/);
  assert.match(waiting,/aria-label="Fiole" disabled/);
  assert.doesNotMatch(waiting,/À vous de jouer/);
  globalThis.__owlbearRuntime={combat,state:{combat,pending:null,resolution:null},playerId:'alice',ready:true,error:''};
  assert.match(renderToStaticMarkup(React.createElement(Panel,{...props,ready:true})),/À vous de jouer/);
  globalThis.__owlbearRuntime.state.pending={id:'pending',defenders:[],answers:{}};
  assert.match(renderToStaticMarkup(React.createElement(Panel,{...props,ready:true})),/Résolution de l’attaque…/);
  delete globalThis.__owlbearRuntime;
  const otherTurn=renderToStaticMarkup(React.createElement(Initiative,{combat:{...combat,turn:1},canManage:false,playerId:'alice',connectionId:'alice'}));
  assert.doesNotMatch(otherTurn,/Terminer mon tour/);
  const gm=renderToStaticMarkup(React.createElement(Initiative,{combat,canManage:true,playerId:'gm',connectionId:'gm'}));
  assert.match(gm,/DEX : 24/);assert.doesNotMatch(gm,/Gérer les tours|Tour précédent|Participant actif/);
 }finally{delete globalThis.__owlbearRuntime;await rm(folder,{recursive:true,force:true})}
});
